-- Durable audit state for the Redis-backed distributed evaluation queue.
CREATE TABLE cluster_workers (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  worker_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  hostname VARCHAR(255) NOT NULL,
  platform VARCHAR(80) NOT NULL,
  architecture VARCHAR(80) NOT NULL,
  cpu_threads INT UNSIGNED NOT NULL,
  memory_mb BIGINT UNSIGNED NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'online',
  resource_busy BOOLEAN NOT NULL DEFAULT FALSE,
  labels_json JSON NOT NULL,
  capabilities_json JSON NOT NULL,
  progress_json JSON NOT NULL,
  current_git_commit CHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  registered_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  last_seen_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_cluster_workers_key (worker_key),
  KEY ix_cluster_workers_status_seen (status, last_seen_at),
  CONSTRAINT ck_cluster_workers_cpu CHECK (cpu_threads BETWEEN 1 AND 4096),
  CONSTRAINT ck_cluster_workers_memory CHECK (memory_mb >= 128)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE cluster_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind VARCHAR(30) NOT NULL,
  priority INT UNSIGNED NOT NULL DEFAULT 100,
  status VARCHAR(30) NOT NULL DEFAULT 'queued',
  git_commit CHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  git_remote VARCHAR(255) NOT NULL DEFAULT 'origin',
  payload_json JSON NOT NULL,
  requirements_json JSON NOT NULL,
  progress_json JSON NOT NULL,
  result_json JSON NULL,
  requested_by VARCHAR(120) NOT NULL,
  worker_id BIGINT UNSIGNED NULL,
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NOT NULL DEFAULT 2,
  lease_expires_at TIMESTAMP(3) NULL,
  error_message TEXT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  claimed_at TIMESTAMP(3) NULL,
  started_at TIMESTAMP(3) NULL,
  finished_at TIMESTAMP(3) NULL,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_cluster_jobs_public_id (public_id),
  UNIQUE KEY uq_cluster_jobs_idempotency (idempotency_key),
  KEY ix_cluster_jobs_queue (status, priority, created_at),
  KEY ix_cluster_jobs_worker_status (worker_id, status),
  KEY ix_cluster_jobs_lease (status, lease_expires_at),
  CONSTRAINT ck_cluster_jobs_kind CHECK (kind IN ('git_update', 'benchmark', 'tournament', 'evaluation')),
  CONSTRAINT ck_cluster_jobs_status CHECK (status IN ('queued', 'claimed', 'running', 'completed', 'failed', 'cancelled')),
  CONSTRAINT ck_cluster_jobs_priority CHECK (priority BETWEEN 1 AND 1000),
  CONSTRAINT ck_cluster_jobs_attempts CHECK (max_attempts BETWEEN 1 AND 10),
  CONSTRAINT fk_cluster_jobs_worker FOREIGN KEY (worker_id) REFERENCES cluster_workers (id)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE cluster_job_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  job_id BIGINT UNSIGNED NOT NULL,
  worker_id BIGINT UNSIGNED NULL,
  event_type VARCHAR(50) NOT NULL,
  detail_json JSON NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_cluster_job_events_job_time (job_id, created_at),
  KEY ix_cluster_job_events_worker_time (worker_id, created_at),
  CONSTRAINT fk_cluster_job_events_job FOREIGN KEY (job_id) REFERENCES cluster_jobs (id) ON DELETE CASCADE,
  CONSTRAINT fk_cluster_job_events_worker FOREIGN KEY (worker_id) REFERENCES cluster_workers (id)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
